/**
 * 字送り（ベタ空け）で組まれた帳票。
 *
 * 実物の納品書・売上伝票は、見出しや品目名を**1文字ずつ離して**組んでいることがある。
 * 組版の字送りなので、文字と文字のあいだに空白があるわけではない。そのまま扱うと
 *
 *   - 品目名が `電 気 掃 除 機` になり、辞書にも品目リストにも一致しない
 *   - 見出しが `商 品 名` になり、**品目名の見出しとして認識できない**
 *     → 段組みも見出し帯の切り離しも効かず、宛名・住所・Telまで表の行として混ざる
 *
 * さらに、太字を「同じ文字を2回刷る」で作っている帳票があり（`売 売 上 上`）、
 * そのままでは見出しも品目名も倍になる。
 */
import { describe, it, expect } from 'vitest'
import { pdfPagesToRows, detectLayout } from './pdfGrid.js'

const t = (text, x, y, w, h) => ({ text, x, y, w: w ?? text.length * 6, h: h ?? 10 })

describe('トークンの中の字送り', () => {
  it('1文字ずつ離れた品目名を1語に戻す', () => {
    const page = { rotate: 0, tokens: [
      t('商品名', 30, 750), t('数量', 150, 750), t('単価', 230, 750),
      t('電 気 掃 除 機', 30, 730, 60), t('2', 150, 730), t('23000', 230, 730),
      t('冷 蔵 庫', 30, 710, 36), t('2', 150, 710), t('125000', 230, 710),
    ]}
    const rows = pdfPagesToRows([page])
    expect(rows.map(r => r[0])).toEqual(['商品名', '電気掃除機', '冷蔵庫'])
  })

  it('2文字以上の塊があるものは詰めない（本当に離れている語を1語にしない）', () => {
    const page = { rotate: 0, tokens: [
      t('品名', 30, 750), t('備考', 150, 750),
      t('豚バラ', 30, 730), t('2003 年 12 月 21 日', 150, 730, 90),
      t('人参', 30, 710), t('国産 冷蔵', 150, 710, 48),
    ]}
    const rows = pdfPagesToRows([page])
    expect(rows[1][1]).toBe('2003 年 12 月 21 日')
    expect(rows[2][1]).toBe('国産 冷蔵')
  })
})

describe('1文字ずつ別トークンの見出し', () => {
  // 見出しだけが字送りで、1文字ずつ別のトークンになっている紙。
  // 実物と同じく、字送りの見出しは**その列の幅いっぱいに広がっている**
  const SPACED_HEAD = { rotate: 0, tokens: [
    t('商', 30, 750, 11), t('品', 68, 750, 11), t('名', 106, 750, 11),
    t('数', 150, 750, 11), t('量', 175, 750, 11),
    t('単', 230, 750, 11), t('価', 255, 750, 11),
    t('豚バラ肉切り落とし', 30, 730, 108), t('2', 150, 730), t('1200', 230, 730),
    t('キャベツ', 30, 710, 48), t('3', 150, 710), t('280', 230, 710),
    t('人参', 30, 690, 24), t('5', 150, 690), t('90', 230, 690),
  ]}

  it('同じマスに入った1文字は空白を挟まずにつなぐ', () => {
    const rows = pdfPagesToRows([SPACED_HEAD])
    expect(rows[0]).toEqual(['商品名', '数量', '単価'])
  })

  it('品目名の見出しとして認識する（段組みと見出し帯の判定がここに乗っている）', () => {
    expect(detectLayout([SPACED_HEAD])).toEqual({ cols: 1, rows: 1, count: 1 })
  })

  it('認識できるので、表の上の宛名や住所は表から外れる', () => {
    const withHead = { rotate: 0, tokens: [
      t('納品書', 225, 800, 36),
      t('東京都千代田区', 53, 785, 84),
      t('○○○○電気 様', 119, 770, 84),
      ...SPACED_HEAD.tokens,
    ]}
    const rows = pdfPagesToRows([withHead])
    expect(rows[0]).toEqual(['商品名', '数量', '単価'])
    expect(rows.some(r => r.join('').includes('東京都'))).toBe(false)
  })

  it('折り返した品目名の続きは、今までどおり空白で区切る', () => {
    const page = { rotate: 0, tokens: [
      t('品名', 30, 750), t('単位', 150, 750), t('単価', 230, 750),
      t('豆乳', 30, 730, 18), t('２００ｍｌ', 51, 730, 45), t('本', 150, 730), t('100', 230, 730),
      t('牛乳', 30, 710), t('本', 150, 710), t('120', 230, 710),
      t('人参', 30, 690), t('本', 150, 690), t('90', 230, 690),
    ]}
    expect(pdfPagesToRows([page])[1][0]).toBe('豆乳 ２００ｍｌ')
  })
})

describe('太字を2回刷りで作っている帳票', () => {
  it('同じ位置に重なった同じ文字は1つにする', () => {
    const page = { rotate: 0, tokens: [
      t('品名', 30, 750), t('単価', 230, 750),
      t('売', 30, 730, 11), t('売', 30, 730, 11),
      t('上', 45, 730, 11), t('上', 45, 730, 11),
      t('1200', 230, 730),
      t('人参', 30, 710), t('90', 230, 710),
    ]}
    expect(pdfPagesToRows([page])[1][0]).toBe('売上')
  })
})

describe('1ページ目が表ではない紙', () => {
  it('品目名の見出しがある最初のページから割り方を見る', () => {
    const cover = { rotate: 0, tokens: [
      t('ＦＡＸ送信のご案内', 57, 511, 108), t('送信先', 72, 451), t('△△△△電気 様', 215, 451, 66),
    ]}
    const table = { rotate: 0, tokens: [
      t('商品名', 30, 750), t('数量', 150, 750),
      t('商品名', 330, 750), t('数量', 450, 750),
      t('豚バラ', 30, 730), t('2', 150, 730),
      t('人参', 330, 730), t('5', 450, 730),
    ]}
    // 1ページ目だけを見ると「見出しの無い紙」になり、段組みが分からなくなる
    expect(detectLayout([cover, table])).toEqual({ cols: 2, rows: 1, count: 2 })
  })
})
